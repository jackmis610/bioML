"""Copy result tables from reports/<v>/metrics.json into README.md and docs/ARCHITECTURE.md.

Numbers in the docs are never typed by hand. Each doc has blocks like

    <!-- BEGIN:headline -->
    ...
    <!-- END:headline -->

whose contents this script regenerates. Run after `make report`:

    uv run python scripts/sync_docs.py --report reports/v2
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]


def _fmt(x: float | None, nd: int = 3) -> str:
    if x is None:
        return "n/a"
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "n/a"


def _delta(new: float, ref: float) -> str:
    return f"{(new - ref) / abs(ref) * 100:+.0f}%"


def headline(r: dict[str, Any]) -> str:
    m = r["models"]
    rows = [
        ("HR-zone coaching heuristic", m["hr_zone"]),
        ("Population-mean curve", m["population_curve"]),
        ("**LightGBM multitask v2**", m["lightgbm"]),
    ]
    out = [
        "| Model | RER MAE | VO2 MAE (mL/min) | LT2 AUC | LT2 Brier | fat-ox MAE (g/min) |",
        "|---|---|---|---|---|---|",
    ]
    for label, s in rows:
        bold = label.startswith("**")
        b = "**" if bold else ""
        out.append(
            f"| {label} | {b}{_fmt(s['rer_mae'], 4)}{b} | {b}{s['vo2_mae_mlmin']:.0f}{b} "
            f"| {b}{_fmt(s['lt2_auc'])}{b} | {b}{_fmt(s['lt2_brier'], 4)}{b} "
            f"| {b}{_fmt(s['substrate']['fat_ox_mae_g_per_min'])}{b} |"
        )
    lgb, pop, hz = m["lightgbm"], m["population_curve"], m["hr_zone"]
    lgb_fat = lgb["substrate"]["fat_ox_mae_g_per_min"]
    pop_fat = pop["substrate"]["fat_ox_mae_g_per_min"]
    out.append("")
    out.append(
        f"Relative to the population curve: RER MAE {_delta(lgb['rer_mae'], pop['rer_mae'])}, "
        f"VO2 MAE {_delta(lgb['vo2_mae_mlmin'], pop['vo2_mae_mlmin'])}, "
        f"LT2 Brier {_delta(lgb['lt2_brier'], pop['lt2_brier'])}, "
        f"fat-ox MAE {_delta(lgb_fat, pop_fat)}. "
        f"Relative to the HR-zone heuristic: RER MAE {_delta(lgb['rer_mae'], hz['rer_mae'])}, "
        f"VO2 MAE {_delta(lgb['vo2_mae_mlmin'], hz['vo2_mae_mlmin'])}."
    )
    p = r["provenance"]
    out.append("")
    out.append(
        f"*{p['k']}-fold subject-wise CV, n = {p['n_subjects']} synthetic subjects "
        f"({p['n_rows']:,} one-second rows), seed {p['seed']}, "
        f"{p['n_estimators']} boosting rounds, "
        f"{p['n_features']} wearable-only features. Generated by `make report` "
        f"({p['generated_at'][:10]}, bioml {p['bioml_version']}).*"
    )
    return "\n".join(out)


def ablations(r: dict[str, Any]) -> str:
    lgb = r["models"]["lightgbm"]
    out = [
        "| Config | Dropped feature groups | #feat | RER MAE | Δ | VO2 MAE | Δ "
        "| LT2 AUC | fat-ox MAE |",
        "|---|---|---|---|---|---|---|---|---|",
        f"| full | – | {r['provenance']['n_features']} | {lgb['rer_mae']:.4f} | – "
        f"| {lgb['vo2_mae_mlmin']:.0f} | – | {lgb['lt2_auc']:.3f} "
        f"| {_fmt(lgb['substrate']['fat_ox_mae_g_per_min'])} |",
    ]
    for name, s in r["ablations"].items():
        out.append(
            f"| {name} | {', '.join(s['dropped_groups'])} | {s['n_features']} "
            f"| {s['rer_mae']:.4f} | {_delta(s['rer_mae'], lgb['rer_mae'])} "
            f"| {s['vo2_mae_mlmin']:.0f} | {_delta(s['vo2_mae_mlmin'], lgb['vo2_mae_mlmin'])} "
            f"| {s['lt2_auc']:.3f} | {_fmt(s['substrate']['fat_ox_mae_g_per_min'])} |"
        )
    return "\n".join(out)


def intensity(r: dict[str, Any]) -> str:
    lgb = r["models"]["lightgbm"]
    out = [
        "| %VO2max bin | rows/fold | RER MAE | RER bias | VO2 MAE | VO2 bias |",
        "|---|---|---|---|---|---|",
    ]
    for (label, n, rmae), (_, _, rb), (_, _, vmae), (_, _, vb) in zip(
        lgb["rer_mae_by_intensity"],
        lgb["rer_bias_by_intensity"],
        lgb["vo2_mae_by_intensity"],
        lgb["vo2_bias_by_intensity"],
        strict=True,
    ):
        if n:
            out.append(f"| {label} | {n:,} | {rmae:.4f} | {rb:+.4f} | {vmae:.0f} | {vb:+.0f} |")
    return "\n".join(out)


def shap_top(r: dict[str, Any], k: int = 6) -> str:
    shap = r["attribution"]["shap_mean_abs_oof"]
    groups = {f: g for g, fs in r["provenance"]["feature_groups"].items() for f in fs}
    out = ["| Head | Top features by out-of-fold mean abs SHAP |", "|---|---|"]
    for head, title in (("rer", "RER"), ("vo2", "VO2"), ("lt2", "P(above LT2)")):
        ranked = sorted(shap[head].items(), key=lambda kv: -kv[1])[:k]
        out.append(f"| {title} | " + ", ".join(f"`{f}` ({groups[f]})" for f, _ in ranked) + " |")
    return "\n".join(out)


def substrate(r: dict[str, Any]) -> str:
    m = r["models"]
    out = [
        "| Model | fat-ox MAE (g/min) | fat-ox bias | gate precision | gate recall "
        "| gate accuracy |",
        "|---|---|---|---|---|---|",
    ]
    for label, s in (
        ("HR-zone heuristic", m["hr_zone"]),
        ("Population curve", m["population_curve"]),
        ("**LightGBM multitask v2**", m["lightgbm"]),
    ):
        sub = s["substrate"]
        out.append(
            f"| {label} | {_fmt(sub['fat_ox_mae_g_per_min'])} "
            f"| {sub['fat_ox_bias_g_per_min']:+.3f} "
            f"| {_fmt(sub['gate_precision'])} | {_fmt(sub['gate_recall'])} "
            f"| {_fmt(sub['gate_accuracy'])} |"
        )
    return "\n".join(out)


def calibration(r: dict[str, Any]) -> str:
    cal = r["models"]["lightgbm"]["calibration"]
    out = [
        f"ECE = {_fmt(cal['ece'], 4)}",
        "",
        "| P(LT2) bin | n | mean predicted | observed rate |",
        "|---|---|---|---|",
    ]
    for lo, hi, n, pred, obs in cal["reliability"]:
        if n:
            out.append(f"| {lo:.1f}-{hi:.1f} | {n:,} | {pred:.3f} | {obs:.3f} |")
    return "\n".join(out)


BLOCKS = {
    "headline": headline,
    "ablations": ablations,
    "intensity": intensity,
    "shap": shap_top,
    "substrate": substrate,
    "calibration": calibration,
}


def sync(doc: Path, r: dict[str, Any]) -> int:
    text = doc.read_text()
    n = 0
    for name, fn in BLOCKS.items():
        pattern = re.compile(rf"(<!-- BEGIN:{name} -->\n)(.*?)(<!-- END:{name} -->)", re.S)
        if pattern.search(text):
            text = pattern.sub(lambda m, fn=fn: m.group(1) + fn(r) + "\n" + m.group(3), text)
            n += 1
    doc.write_text(text)
    return n


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--report", type=Path, default=REPO / "reports" / "v2")
    args = p.parse_args()
    r = json.loads((args.report / "metrics.json").read_text())
    for doc in (REPO / "README.md", REPO / "docs" / "ARCHITECTURE.md"):
        if doc.exists():
            print(f"{doc.relative_to(REPO)}: {sync(doc, r)} block(s) synced")


if __name__ == "__main__":
    main()
